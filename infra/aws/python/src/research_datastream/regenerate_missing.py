#!/usr/bin/env python3
"""
Find NRDS simulations whose outputs are missing and relaunch them (issue #397).

    python -m research_datastream.regenerate_missing \\
        --start 20260820 --end 20260823 \\
        --datastreams cfe_nom --run-types short_range --init-cycles 22,23 \\
        --out ./regenerate --dry-run

The deployed EventBridge schedules are the catalogue of simulations. Each one
carries the clean, rendered execution for a datastream / run type / init /
member / VPU, with DAILY standing in for the date. For every date in the range
and every schedule matching the filters this script:

  1. resolves the output prefix and checks for the object the checker lambda
     treats as success (merkdir.file, or forcings_metadata/metadata.csv);
  2. for each missing simulation, renders its execution. By default that is the
     execution.json the commander lambda stored beside the outputs, stripped of
     the fields specific to the failed run (instance id, t0, retry_attempt ...).
     When none was stored, or with --source schedule, the schedule's payload is
     used. Either way DAILY is resolved to the date being regenerated;
  3. writes the execution to --out and, unless --dry-run, issues
     `stepfunctions start-execution` for it.

Simulations are skipped when they are too recent to judge (--min-age-hours)
or already being regenerated. Inputs are not checked: an execution whose
inputs are missing fails in the state machine like any other run.

Author: Jordan Laser
jlaser@lynker.com
"""

from __future__ import annotations

import argparse
import copy
import json
import re
import sys
import time
from concurrent.futures import ThreadPoolExecutor
from dataclasses import dataclass
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Dict, Iterable, List, Optional, Tuple

REGION = "us-east-1"
NAME_PREFIX = "regen"

# Keys of a clean execution: the shape the schedules submit. Everything else
# is added by the state machine's lambdas during a run.
EXECUTION_KEYS = ("commands", "run_options", "instance_parameters", "datastream_command_options")
# Added to instance_parameters by the starter lambda.
RUN_INSTANCE_KEYS = ("InstanceId", "MaxCount", "MinCount", "InstanceMarketOptions", "SubnetId")

# Same patterns the commander and checker lambdas use to read a command.
BUCKET_RE = re.compile(r"(?i)--s3_bucket[=\s']+([^\s']+)")
PREFIX_RE = re.compile(r"(?i)--s3_prefix[=\s']+([^\s']+)")
DATASTREAM_CMD_RE = re.compile(r"(?i)/scripts/datastream[=\s']+([^\s']+)")

# DAILY as the commander replaces it, but leaving `-s DAILY`, which tells
# datastreamcli to simulate one day; -e then pins which day.
DAILY_RE = re.compile(r"(?<!-s )(?<!--START_DATE )(?<![A-Za-z0-9])DAILY(?![A-Za-z0-9])")
START_DAILY_RE = re.compile(r"(-s|--START_DATE)\s+DAILY\b")
END_RE = re.compile(r"(?:^|\s)(?:-e|--END_DATE)\s")

# Shell the templates run on the instance to find the run date from the clock,
# as it reads on the target date: today is the date, yesterday the day before,
# and the hour is the end of the day, so a cycle is never "not yet run today".
CLOCK = {
    "$(date -u +%Y%m%d)": lambda d: d,
    "$(date -u -d yesterday +%Y%m%d)": lambda d: (datetime.strptime(d, "%Y%m%d") - timedelta(days=1)).strftime("%Y%m%d"),
    "$(date -u +%H)": lambda d: "23",
}
# Any other clock read that yields a date or hour. Timestamps such as
# +%Y%m%d%H%M%S are left alone.
UNRESOLVED_CLOCK_RE = re.compile(r"\$\(date\b[^)]*\+%(?:Y%m%d|H)\)")

# Schedule names, as the datastream modules under
# infra/aws/terraform/services/nrds/datastreams name them.
SCHEDULE_PATTERNS = (
    # short_range_fcst23_vpu01_schedule_cfe_nom_prod
    # medium_range_fcst00_mem1_vpu01_schedule_lstm_0_prod
    r"(?P<run_type>[a-z_]+?)_fcst(?P<init>\d{2})(?:_mem(?P<member>\d+))?_vpu(?P<vpu>[0-9A-Z]+)_schedule_(?P<datastream>\w+)",
    # short_range_fcst23_forcing_schedule_prod
    r"(?P<run_type>[a-z_]+?)_fcst(?P<init>\d{2})_(?P<datastream>forcing)_schedule",
    # restart_init05_schedule_prod
    r"(?P<datastream>[a-z_]+?)_init(?P<init>\d{2})_schedule",
)
# Not regenerated by this tool.
IGNORED_DATASTREAMS = {"qkrig"}


@dataclass(frozen=True)
class Simulation:
    datastream: str
    run_type: str
    init: str
    member: str
    vpu: str
    schedule: str

    def label(self) -> str:
        parts = [self.datastream, self.run_type, f"init{self.init}"]
        if self.member:
            parts.append(f"mem{self.member}")
        if self.vpu:
            parts.append(f"VPU_{self.vpu}")
        return " ".join(p for p in parts if p)


@dataclass
class Job:
    sim: Simulation
    date: str
    template: dict
    state_machine_arn: str
    bucket: str = ""
    prefix: str = ""
    status: str = ""
    detail: str = ""
    source: str = ""
    execution: Optional[dict] = None
    name: str = ""


# --------------------------------------------------------------------------- #
# Schedules
# --------------------------------------------------------------------------- #
def parse_schedule_name(name: str, environment: str) -> Optional[Simulation]:
    suffix = f"_{environment}"
    if not name.endswith(suffix):
        return None
    stem = name[: -len(suffix)]
    for pattern in SCHEDULE_PATTERNS:
        m = re.fullmatch(pattern, stem)
        if m:
            g = m.groupdict()
            if g["datastream"] in IGNORED_DATASTREAMS:
                return None
            return Simulation(
                datastream=g["datastream"],
                run_type=g.get("run_type") or "",
                init=g["init"],
                member=g.get("member") or "",
                vpu=g.get("vpu") or "",
                schedule=name,
            )
    return None


def select(sims: Iterable[Simulation], filters: Dict[str, Optional[set]]) -> List[Simulation]:
    """Simulations matching every filter. A filter of None matches anything,
    and a filter only applies where the simulation has that dimension: the
    CONUS-wide forcing run passes a VPU filter, short range a member filter.
    Choose those datastreams in or out with --datastreams."""
    out = [
        sim for sim in sims
        if all(allowed is None or not getattr(sim, key) or getattr(sim, key) in allowed
               for key, allowed in filters.items())
    ]
    return sorted(out, key=lambda s: (s.datastream, s.run_type, s.init, s.member, s.vpu))


def list_schedule_names(scheduler, group: str) -> List[str]:
    names = []
    for page in scheduler.get_paginator("list_schedules").paginate(GroupName=group):
        names.extend(s["Name"] for s in page["Schedules"])
    return names


def schedule_target(scheduler, name: str, group: str) -> Tuple[str, dict]:
    """The state machine a schedule targets and the execution it submits."""
    target = json.loads(scheduler.get_schedule(Name=name, GroupName=group)["Target"]["Input"])
    return target["StateMachineArn"], json.loads(target["Input"])


# --------------------------------------------------------------------------- #
# Executions
# --------------------------------------------------------------------------- #
def command_value(execution: dict, pattern: re.Pattern) -> Optional[str]:
    value = None
    for cmd in execution.get("commands", []):
        m = pattern.search(cmd)
        if m:
            value = m.group(1)
    return value


def location(execution: dict) -> Tuple[str, str]:
    """(bucket, prefix) an execution writes to."""
    opts = execution.get("datastream_command_options")
    if opts and "s3_bucket" in opts:
        return opts["s3_bucket"], opts["s3_prefix"]
    bucket = command_value(execution, BUCKET_RE)
    prefix = command_value(execution, PREFIX_RE)
    if not bucket or not prefix:
        raise ValueError("execution names no --s3_bucket / --s3_prefix")
    return bucket, prefix.rstrip("/")


def execution_key(prefix: str) -> str:
    """Where the commander lambda stores the execution it ran."""
    if "forcing" in prefix:
        return f"{prefix}/metadata/execution.json"
    return f"{prefix}/datastream-metadata/execution.json"


def resolve_date(execution: dict, date: str, strict: bool = True) -> dict:
    """Pin an execution to a date: every DAILY becomes the date, the clock
    reads in CLOCK become their value on that date, and a `-s DAILY` without
    an end date gets `-e <date>0000`, since datastreamcli otherwise simulates
    today. Raises ValueError for a clock read it cannot pin."""
    out = copy.deepcopy(execution)
    commands = []
    for cmd in out.get("commands", []):
        cmd = DAILY_RE.sub(date, cmd)
        for expr, value in CLOCK.items():
            cmd = cmd.replace(expr, value(date))
        unresolved = UNRESOLVED_CLOCK_RE.search(cmd)
        if unresolved and strict:
            raise ValueError(f"command reads the clock: {unresolved.group(0)}")
        if START_DAILY_RE.search(cmd) and not END_RE.search(cmd):
            cmd = START_DAILY_RE.sub(lambda m: f"{m.group(0)} -e {date}0000", cmd, count=1)
        commands.append(cmd)
    out["commands"] = commands
    if "datastream_command_options" in out:
        opts = out["datastream_command_options"]
        for key, value in opts.items():
            if isinstance(value, str):
                opts[key] = DAILY_RE.sub(date, value)
    return out


def clean(execution: dict) -> dict:
    """An execution as the state machine stored it, reduced to what a fresh
    run is submitted with."""
    out = {k: copy.deepcopy(execution[k]) for k in EXECUTION_KEYS if k in execution}
    for key in RUN_INSTANCE_KEYS:
        out.get("instance_parameters", {}).pop(key, None)
    return out


def execution_name(job: Job, tag: str) -> str:
    """Step Functions names: 80 characters of [A-Za-z0-9_-]."""
    sim = job.sim
    parts = [NAME_PREFIX, sim.datastream, sim.run_type, job.date, f"i{sim.init}"]
    if sim.member:
        parts.append(f"m{sim.member}")
    if sim.vpu:
        parts.append(f"v{sim.vpu}")
    stem = "_".join(p for p in parts if p)
    return re.sub(r"[^A-Za-z0-9_-]", "-", f"{stem}_{tag}")[:80]


def name_stem(name: str) -> str:
    return name.rsplit("_", 1)[0]


# --------------------------------------------------------------------------- #
# S3
# --------------------------------------------------------------------------- #
def _keys(s3, bucket: str, prefix: str, limit: int = 1000) -> List[str]:
    resp = s3.list_objects_v2(Bucket=bucket, Prefix=prefix, MaxKeys=limit)
    return [o["Key"] for o in resp.get("Contents", [])]


def is_complete(s3, execution: dict, bucket: str, prefix: str) -> bool:
    """Whether the outputs the checker lambda looks for exist.

    Datastream runs leave merkdir.file; forcing and restart runs leave
    metadata/forcings_metadata/metadata.csv. Restart currently writes the
    latter with a doubled slash, so slashes are collapsed before matching."""
    if command_value(execution, DATASTREAM_CMD_RE):
        return bool(_keys(s3, bucket, f"{prefix}/merkdir.file", 1))
    keys = _keys(s3, bucket, f"{prefix}/metadata/forcings_metadata")
    return any("forcings_metadata/metadata.csv" in re.sub("/+", "/", k) for k in keys)


def get_json(s3, bucket: str, key: str) -> Optional[dict]:
    try:
        body = s3.get_object(Bucket=bucket, Key=key)["Body"].read()
    except s3.exceptions.NoSuchKey:
        return None
    return json.loads(body)


def exists(s3, url: str) -> bool:
    bucket, _, key = url[len("s3://"):].partition("/")
    return bool(_keys(s3, bucket, key, 1))


# --------------------------------------------------------------------------- #
# Planning
# --------------------------------------------------------------------------- #
def dates(start: str, end: str) -> List[str]:
    d0 = datetime.strptime(start, "%Y%m%d")
    d1 = datetime.strptime(end or start, "%Y%m%d")
    if d1 < d0:
        raise ValueError("--end is before --start")
    return [(d0 + timedelta(days=i)).strftime("%Y%m%d") for i in range((d1 - d0).days + 1)]


def too_recent(job: Job, now: datetime, min_age_hours: float) -> bool:
    cycle = datetime.strptime(job.date + job.sim.init, "%Y%m%d%H").replace(tzinfo=timezone.utc)
    return now - cycle < timedelta(hours=min_age_hours)


def render(s3, job: Job, source: str) -> None:
    """Fill job.execution from the stored execution or the schedule."""
    if source == "execution":
        stored = get_json(s3, job.bucket, execution_key(job.prefix))
        if stored is not None:
            if job.sim.member and job.sim.member != "1":
                # The commander shifts medium-range forcings by member on the
                # first attempt; a stored execution is already shifted.
                job.detail = "stored execution already member-shifted; used schedule"
            else:
                execution = resolve_date(clean(stored), job.date)
                try:
                    stored_at = location(execution)
                except ValueError:
                    stored_at = None
                if stored_at == (job.bucket, job.prefix):
                    job.execution, job.source = execution, "stored execution"
                    return
                job.detail = f"stored execution writes to {stored_at}; used schedule"
    job.execution = resolve_date(job.template, job.date)
    job.source = "schedule"


def plan(args, scheduler, s3, sfn) -> List[Job]:
    filters = {
        "datastream": args.datastreams,
        "run_type": args.run_types,
        "init": args.init_cycles,
        "member": args.members,
        "vpu": args.vpus,
    }
    names = list_schedule_names(scheduler, args.schedule_group)
    sims = select(
        (s for s in (parse_schedule_name(n, args.environment) for n in names) if s), filters
    )
    if not sims:
        raise SystemExit("No schedules match the filters.")
    print(f"{len(sims)} scheduled simulations match the filters", file=sys.stderr)

    with ThreadPoolExecutor(args.workers) as pool:
        targets = list(pool.map(lambda s: schedule_target(scheduler, s.schedule, args.schedule_group), sims))

    now = datetime.now(timezone.utc)
    tag = args.tag or now.strftime("%Y%m%dT%H%M%S")
    jobs = []
    for date in dates(args.start, args.end):
        for sim, (arn, template) in zip(sims, targets):
            job = Job(sim=sim, date=date, template=template, state_machine_arn=args.state_machine_arn or arn)
            job.bucket, job.prefix = location(resolve_date(template, date, strict=False))
            if too_recent(job, now, args.min_age_hours):
                job.status, job.detail = "skipped", f"less than {args.min_age_hours:g}h old"
            jobs.append(job)

    def check(job: Job) -> None:
        if job.status:
            return
        if is_complete(s3, job.template, job.bucket, job.prefix):
            job.status = "complete"
            return
        try:
            render(s3, job, args.source)
        except ValueError as e:
            job.status, job.detail = "skipped", str(e)
            return
        job.name = execution_name(job, tag)
        job.status = "missing"

    with ThreadPoolExecutor(args.workers) as pool:
        list(pool.map(check, jobs))

    missing = [j for j in jobs if j.status == "missing"]
    running = running_stems(sfn, {j.state_machine_arn for j in missing if j.status == "missing"})
    for job in missing:
        if job.status == "missing" and name_stem(job.name) in running:
            job.status, job.detail = "skipped", "already being regenerated"

    return jobs


def running_stems(sfn, arns: Iterable[str]) -> set:
    stems = set()
    for arn in arns:
        pages = sfn.get_paginator("list_executions").paginate(stateMachineArn=arn, statusFilter="RUNNING")
        for page in pages:
            stems.update(
                name_stem(e["name"]) for e in page["executions"] if e["name"].startswith(NAME_PREFIX + "_")
            )
    return stems


# --------------------------------------------------------------------------- #
# Output
# --------------------------------------------------------------------------- #
def write(jobs: List[Job], out: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    manifest = []
    for job in jobs:
        entry = {
            "datastream": job.sim.datastream,
            "run_type": job.sim.run_type,
            "init": job.sim.init,
            "member": job.sim.member,
            "vpu": job.sim.vpu,
            "date": job.date,
            "status": job.status,
            "detail": job.detail,
            "output": f"s3://{job.bucket}/{job.prefix}",
        }
        if job.execution is not None and job.status in ("missing", "submitted", "failed"):
            path = out / "executions" / f"{job.name}.json"
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(json.dumps(job.execution, indent=2) + "\n")
            entry.update(source=job.source, name=job.name, execution=str(path.relative_to(out)),
                         state_machine_arn=job.state_machine_arn)
        manifest.append(entry)
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")


def summary(jobs: List[Job], dry_run: bool) -> str:
    counts: Dict[str, int] = {}
    for job in jobs:
        counts[job.status] = counts.get(job.status, 0) + 1
    lines = [
        "## Missing NRDS simulations",
        "",
        "Dry run: nothing was submitted." if dry_run else "",
        "",
        "| status | count |",
        "| --- | ---: |",
    ]
    lines += [f"| {k} | {v} |" for k, v in sorted(counts.items())]
    rows = [j for j in jobs if j.status not in ("complete",)]
    if rows:
        lines += ["", "| date | simulation | status | source | detail |", "| --- | --- | --- | --- | --- |"]
        lines += [f"| {j.date} | {j.sim.label()} | {j.status} | {j.source} | {j.detail} |" for j in rows]
    return "\n".join(lines) + "\n"


# --------------------------------------------------------------------------- #
# CLI
# --------------------------------------------------------------------------- #
def _set(value: str) -> Optional[set]:
    value = (value or "").strip()
    if value in ("", "all"):
        return None
    return {v.strip() for v in value.split(",") if v.strip()}


def _inits(value: str) -> Optional[set]:
    found = _set(value)
    return None if found is None else {f"{int(v):02d}" for v in found}


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(
        prog="research_datastream.regenerate_missing",
        description="Find NRDS simulations with missing outputs and relaunch them.",
    )
    parser.add_argument("--start", required=True, help="First date, YYYYMMDD")
    parser.add_argument("--end", default="", help="Last date, YYYYMMDD (default: --start)")
    parser.add_argument("--datastreams", type=_set, default=None, help="e.g. cfe_nom,lstm_0 (default: all)")
    parser.add_argument("--run-types", type=_set, default=None, help="e.g. short_range,medium_range (default: all)")
    parser.add_argument("--init-cycles", type=_inits, default=None, help="e.g. 00,06,12 (default: all)")
    parser.add_argument("--members", type=_set, default=None, help="medium-range members, e.g. 1 (default: all)")
    parser.add_argument("--vpus", type=_set, default=None, help="e.g. 01,03W,10L (default: all)")
    parser.add_argument("--source", choices=("execution", "schedule"), default="execution",
                        help="execution: the stored execution.json, cleaned, falling back to the schedule. "
                             "schedule: the deployed schedule's payload")
    parser.add_argument("--environment", default="prod", help="Schedule name suffix")
    parser.add_argument("--schedule-group", default="default")
    parser.add_argument("--state-machine-arn", default="", help="Override the schedules' target")
    parser.add_argument("--min-age-hours", type=float, default=12,
                        help="Leave cycles younger than this to the schedules and their retries")
    parser.add_argument("--max-executions", type=int, default=500, help="Refuse to submit more than this")
    parser.add_argument("--interval", type=float, default=1.0, help="Seconds between submissions")
    parser.add_argument("--tag", default="", help="Suffix for execution names (default: a UTC timestamp)")
    parser.add_argument("--workers", type=int, default=16)
    parser.add_argument("--region", default=REGION)
    parser.add_argument("--out", default="./regenerate-missing", help="Executions and manifest go here")
    parser.add_argument("--summary", default="", help="Append a markdown summary here")
    parser.add_argument("--dry-run", action="store_true", help="Render and report, submit nothing")
    args = parser.parse_args(argv)

    import boto3

    session = boto3.Session(region_name=args.region)
    scheduler, s3, sfn = session.client("scheduler"), session.client("s3"), session.client("stepfunctions")

    jobs = plan(args, scheduler, s3, sfn)
    order = [j for j in jobs if j.status == "missing"]

    if not args.dry_run and len(order) > args.max_executions:
        write(jobs, Path(args.out))
        print(f"{len(order)} executions exceed --max-executions {args.max_executions}; nothing submitted. "
              "Narrow the filters or raise the limit.", file=sys.stderr)
        return 2

    rc = 0
    for i, job in enumerate(order):
        if args.dry_run:
            continue
        try:
            resp = sfn.start_execution(
                stateMachineArn=job.state_machine_arn, name=job.name, input=json.dumps(job.execution)
            )
            job.status, job.detail = "submitted", resp["executionArn"]
            print(f"[{i + 1}/{len(order)}] {job.name}", file=sys.stderr)
        except Exception as e:  # keep going; the manifest records it
            job.status, job.detail = "failed", str(e)
            rc = 1
            print(f"[{i + 1}/{len(order)}] {job.name} failed: {e}", file=sys.stderr)
        if i + 1 < len(order):
            time.sleep(args.interval)

    write(jobs, Path(args.out))
    text = summary(jobs, args.dry_run)
    print(text)
    if args.summary:
        with open(args.summary, "a") as fp:
            fp.write(text)
    return rc


if __name__ == "__main__":
    sys.exit(main())
